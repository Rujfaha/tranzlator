// Regenerates the LANGUAGES block in shared/languages.ts. Run, then commit the result:
//   node scripts/gen-languages.mjs
// Names are baked in so the app never calls Intl at runtime (Hermes).
//
// Codes: the "Neural Machine Translation model" table on
// https://cloud.google.com/translate/docs/languages (Google Cloud Translation, read 2026-11-02).
// Where the page lists two codes ("fil or tl", "iw or he", "jw or jv", "zh-CN or zh") the modern one
// is used here and the other is an alias in shared/languages.ts.
// Dropped as redundant: "French (French)" fr-FR (same language as fr).
import { readFileSync, writeFileSync } from "node:fs";

const CODES = `
ab ace ach af sq alz am ar hy as awa ay az ban bm ba eu btx bts bbc be bem bn bew bho bik bs br bg
bua yue ca ceb ny zh-CN zh-TW cv co crh hr cs da din dv doi dov nl dz en eo et ee fj fil fi fr fr-CA
fy ff gaa gl lg ka de el gn gu ht cnh ha haw he hil hi hmn hu hrx is ig ilo id ga it ja jv kn pam kk
km cgg rw ktu gom ko kri ku ckb ky lo ltg la lv lij li ln lt lmo luo lb mk mai mak mg ms ms-Arab ml
mt mi mr chm mni-Mtei min lus mn my nr new ne nso no nus oc or om pag pap ps fa pl pt pt-PT pt-BR pa
pa-Arab qu rom ro rn ru sm sg sa gd sr st crs shn sn scn szl sd si sk sl so es su sw ss sv tg ta tt
te tet th ti ts tn tr tk ak uk ur ug uz vi cy xh yi yo yua zu
`.trim().split(/\s+/);

// Hand-written names [th, en]: codes Intl returns bare (not in CLDR), and ones whose Intl style does not suit the UI.
const FIX = {
  "zh-CN": ["จีน (ตัวย่อ)", "Chinese (Simplified)"],
  "zh-TW": ["จีน (ตัวเต็ม)", "Chinese (Traditional)"],
  "fr-CA": ["ฝรั่งเศส (แคนาดา)", "French (Canadian)"],
  "pt-PT": ["โปรตุเกส (โปรตุเกส)", "Portuguese (Portugal)"],
  "pt-BR": ["โปรตุเกส (บราซิล)", "Portuguese (Brazil)"],
  ku: ["เคิร์ด (กุรมันจี)", "Kurdish (Kurmanji)"],
  ckb: ["เคิร์ด (โซรานี)", "Kurdish (Sorani)"],
  alz: ["อาลูร์", "Alur"],
  btx: ["บาตักการอ", "Batak Karo"],
  bts: ["บาตักซีมาลุงกุน", "Batak Simalungun"],
  dov: ["ดอมเบ", "Dombe"],
  cnh: ["ฮากาชิน", "Hakha Chin"],
  hrx: ["ฮุนสริก", "Hunsrik"],
  ktu: ["คิตูบา", "Kituba"],
  yua: ["มายายูคาเทก", "Yucatec Maya"],
};

// English names where Intl differs from what people (and Google's page) call the language, so search finds it.
const EN_FIX = { bn: "Bengali", mi: "Maori", crs: "Seychellois Creole", rom: "Romani" };

const th = new Intl.DisplayNames(["th"], { type: "language" });
const en = new Intl.DisplayNames(["en"], { type: "language" });
const rows = CODES.map((code) => {
  const [t, e] = FIX[code] ?? [th.of(code), EN_FIX[code] ?? en.of(code)];
  if (t === code || e === code) throw new Error(`Intl has no name for "${code}": add it to FIX`);
  return { code, th: t, en: e };
}).sort((a, b) => a.th.localeCompare(b.th, "th") || a.code.localeCompare(b.code));

const target = new URL("../shared/languages.ts", import.meta.url);
const block = `// <generated by scripts/gen-languages.mjs>\nexport const LANGUAGES: readonly Language[] = [\n${rows
  .map((r) => `  ${JSON.stringify(r)},`)
  .join("\n")}\n];\n// </generated>`;
const next = readFileSync(target, "utf8").replace(/\/\/ <generated[\s\S]*?\/\/ <\/generated>/, () => block);
writeFileSync(target, next);
console.log(`wrote ${rows.length} languages`);
